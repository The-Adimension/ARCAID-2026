"""Cross-check the analysis tables against each other and write data/CHECKS.md.

  python -I check_tables.py DATA_DIR

Checks:
  1. Engine replay against the harness record (replay.csv): every match flag.
  2. Logged actions (events) against replayed actions (actions): counts per game-run, and agreement of
     board_changed, game_over and level completion, action by action. A final-level win is logged as `done`
     rather than `level_completed`, so it is reported separately.
  3. Turns against logged actions: does every turn whose tool calls executed actions have logged actions?
  4. Coverage: which runs have turns, calls and events.
The report states what does not match; nothing is corrected.
"""
import csv, gzip, sys
from collections import Counter, defaultdict
from pathlib import Path

d = Path(sys.argv[1])
rd = lambda n: csv.DictReader(gzip.open(d / n, "rt") if n.endswith(".gz") else open(d / n))
out = ["# Consistency checks", "", "Generated by `Tools/analysis/check_tables.py`. Nothing is corrected; mismatches are reported.", ""]

rep = list(rd("replay.csv"))
whole = [r for r in rep if r["trial"] == "0"]; trials = [r for r in rep if r["trial"] == "1"]
out += ["## 1. Engine replay against the harness record", "",
        "| | Game-runs | Match |", "|---|---|---|",
        f"| Whole-game runs: levels completed | {len(whole)} | {sum(r['levels_match'] == '1' for r in whole)} |",
        f"| Whole-game runs: actions per level | {len(whole)} | {sum(r['actions_per_level_match'] == '1' for r in whole)} |",
        f"| Whole-game runs: RHAE score | {len(whole)} | {sum(r['score_match'] == '1' for r in whole)} |",
        f"| Level trials: cleared or not | {len(trials)} | {sum(r['levels_match'] == '1' for r in trials)} |",
        f"| Actions replayed | {sum(int(r['actions']) for r in rep):,} | |", ""]

acts = {}
for r in rd("actions.csv.gz"):
    acts[(r["run_id"], r["game_run"], int(r["action_index"]))] = r
ev = {}
for r in rd("events.csv.gz"):
    if r["pass"] != "0":
        continue
    ev[(r["run_id"], r["game_run"], int(r["action_num"]))] = r
runs_with_events = {k[0] for k in ev}
a_keys = {k for k in acts if k[0] in runs_with_events}
both = a_keys & set(ev)
agree = Counter()
for k in both:
    a, e = acts[k], ev[k]
    agree["board_changed"] += a["board_changed"] == e["board_changed"]
    agree["game_over"] += a["game_over"] == e["game_over"]
    if a["level_completed"] == e["level_completed"]:
        agree["level_completed"] += 1
    elif a["level_completed"] == "1" and e["level_completed"] == "0":
        agree["final_win_logged_as_done"] += 1
out += ["## 2. Logged actions against replayed actions", "",
        f"Runs with event logs: {len(runs_with_events)}. Replayed actions in those runs: {len(a_keys):,}; logged actions: "
        f"{sum(1 for k in ev if k[0] in runs_with_events):,}; present in both: {len(both):,}.", "",
        "| Field | Agree | Of |", "|---|---|---|"]
for f in ("board_changed", "game_over", "level_completed"):
    out.append(f"| {f} | {agree[f]:,} | {len(both):,} |")
out += [f"| level completion replayed but logged as `done` (final-level win) | {agree['final_win_logged_as_done']:,} | |", ""]

turns = list(rd("turns.csv.gz"))
ev_by_turn = Counter((k[0], k[1], e["analysis_step"]) for k, e in ev.items())
t_exec = [t for t in turns if t["pass"] == "0" and int(t["calls_action"]) > 0]
with_ev = sum(ev_by_turn.get((t["run_id"], t["game_run"], t["analysis_step"]), 0) > 0 for t in t_exec if t["run_id"] in runs_with_events)
n_exec = sum(1 for t in t_exec if t["run_id"] in runs_with_events)
out += ["## 3. Turns against logged actions", "",
        f"Turns whose tool calls called `action(...)`: {n_exec:,}; of these, turns with at least one logged action: {with_ev:,}.",
        "A turn can call `action(...)` without executing one (for example an invalid action rejected by the harness).", ""]

cov = defaultdict(lambda: Counter())
for t in turns:
    cov[t["run_id"]]["turns"] += 1
for r in rd("calls.csv.gz"):
    cov[r["run_id"]]["calls"] += 1
for k in ev:
    cov[k[0]]["events"] += 1
for r in rep:
    cov[r["run_id"]]["replayed_actions"] += int(r["actions"])
out += ["## 4. Coverage per run", "", "| Run | Replayed actions | Logged actions | Turns | Model calls |", "|---|---|---|---|---|"]
for run in sorted(cov):
    c = cov[run]
    out.append(f"| `{run}` | {c['replayed_actions']:,} | {c['events']:,} | {c['turns']:,} | {c['calls']:,} |")
(d / "CHECKS.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:40]))
