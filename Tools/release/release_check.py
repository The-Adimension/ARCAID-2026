"""Scan this repository for anything that must be reviewed before it is made public.

  python -I release_check.py REPO_ROOT > Documentation/RELEASE-CHECKS.md

Checks (each finding lists file and line; nothing is changed):
  1. Secrets: API keys and tokens by pattern (Kaggle, Hugging Face, GitHub, OpenAI/Anthropic-style, AWS, private keys).
  2. E-mail addresses.
  3. Local or private paths (home directories, Windows user folders, session scratch paths).
  4. References to private repositories.
  5. Large or binary files (pickles, archives, anything over 5 MB): candidates for external hosting.
  6. Competition data: game files or hidden-set material copied into the repository.
  7. Kaggle notebooks that are still private (from run.json), which the README links to.
  8. Third-party notebooks our notebooks contain, with the licence status recorded in Documentation/REFERENCES.md.
The report is a review list, not a verdict: each finding needs a human decision.
"""
import json, re, sys
from collections import defaultdict
from pathlib import Path

root = Path(sys.argv[1])
SKIP_DIRS = {".git"}
TEXT_EXT = {".py", ".md", ".txt", ".csv", ".json", ".jsonl", ".ipynb", ".patch", ".tsv", ".out", ".diff", ".cff", ""}
PATTERNS = {
    "secret: Kaggle key": re.compile(r'"key"\s*:\s*"[0-9a-f]{32}"|KAGGLE_KEY\s*[=:]\s*\S{8,}'),
    "secret: Hugging Face token": re.compile(r"\bhf_[A-Za-z0-9]{30,}\b"),
    "secret: GitHub token": re.compile(r"\bgh[pousr]_[A-Za-z0-9]{30,}\b|github_pat_[A-Za-z0-9_]{40,}"),
    "secret: API key (sk-)": re.compile(r"\bsk-(ant-|proj-)?[A-Za-z0-9_-]{20,}\b"),
    "secret: AWS key": re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    "secret: private key": re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    "e-mail address": re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b"),
    "local path": re.compile(r"(/home/[a-z_][a-z0-9_-]*/|/Users/[A-Za-z]|[A-Z]:\\\\?Users\\\\?|/tmp/claude-|/root/\.)"),
    "private repository reference": re.compile(r"habanwer/ARCAID3\b|github\.com/habanwer/(?!autoresearch-MIL)[A-Za-z0-9_-]+"),
}
EMAIL_OK = {"noreply@anthropic.com"}

findings = defaultdict(list)
large, binary, compdata = [], [], []
for p in sorted(root.rglob("*")):
    if any(part in SKIP_DIRS for part in p.parts) or not p.is_file():
        continue
    rel = p.relative_to(root).as_posix()
    size = p.stat().st_size
    if rel.startswith("Tools/release/"):
        continue
    if size > 5 * 1024 * 1024:
        large.append((rel, size))
    if p.suffix in {".pkl", ".pickle", ".zip", ".gz", ".parquet", ".npz", ".pt", ".safetensors", ".bin"}:
        binary.append((rel, size))
    if re.search(r"environment_files|/games?/[a-z]{2}\d{2}[^/]*\.py$|games\.pkl|intermediate_states\.pkl", rel):
        compdata.append(rel)
    if p.suffix not in TEXT_EXT or size > 20 * 1024 * 1024:
        continue
    try:
        text = p.read_text(encoding="utf-8", errors="replace")
    except Exception:
        continue
    for i, line in enumerate(text.splitlines(), 1):
        for name, rx in PATTERNS.items():
            for m in rx.finditer(line):
                if name == "e-mail address" and (m.group(0) in EMAIL_OK or m.group(0).endswith((".png", ".jpg"))):
                    continue
                findings[name].append((rel, i, m.group(0)[:80]))

out = ["# Release checks", "",
       "Generated by `Tools/release/release_check.py`. Every item below needs a human decision before this repository, "
       "its Kaggle notebooks or its datasets are made public. Nothing has been changed by the check.", ""]
order = [k for k in PATTERNS]
out += ["## Summary", "", "| Check | Findings |", "|---|---|"]
for k in order:
    out.append(f"| {k} | {len(findings[k])} |")
out += [f"| large files (> 5 MB) | {len(large)} |", f"| binary files (pickle, archive, parquet, weights) | {len(binary)} |",
        f"| competition data paths | {len(compdata)} |", ""]
for k in order:
    if findings[k]:
        uniq = defaultdict(list)
        for rel, i, s in findings[k]:
            uniq[s].append(f"{rel}:{i}")
        out += [f"## {k}", "", "| Match | Where (first 3) | Count |", "|---|---|---|"]
        for s, where in sorted(uniq.items(), key=lambda x: -len(x[1]))[:60]:
            out.append(f"| `{s}` | {', '.join(where[:3])} | {len(where)} |")
        out.append("")
for title, items in (("Large files (> 5 MB)", large), ("Binary files", binary)):
    if items:
        out += [f"## {title}", "", "| File | Bytes |", "|---|---|"] + [f"| `{r}` | {s:,} |" for r, s in items] + [""]
if compdata:
    out += ["## Competition data paths", ""] + [f"- `{r}`" for r in compdata] + [""]

# Kaggle notebook visibility
meta_priv = {}
for p in root.glob("**/run.json"):
    r = json.loads(p.read_text())
    meta_priv[r["kernel"]] = r.get("private_on_kaggle_at_collection")
out += ["## Kaggle notebooks still private", "",
        "The author's instruction is that every notebook used for the competitions is made public with its logs and outputs. "
        "Visibility is as recorded when the runs were collected.", ""]
pv = sorted(k for k, v in meta_priv.items() if v)
out += [f"- `{k}`" for k in pv] or ["- none"]
out += ["", f"{len(pv)} of {len(meta_priv)} notebooks are private.", ""]

# Third-party licences
ref = (root / "Documentation" / "REFERENCES.md").read_text() if (root / "Documentation" / "REFERENCES.md").exists() else ""
tbv = [l.split("|")[2].strip() for l in ref.splitlines() if l.startswith("| N") and "To verify on page" in l]
out += ["## Third-party notebooks whose licence is not yet verified", "",
        "Our notebooks contain the cells of these notebooks unchanged. Open each page and record its licence in "
        "`Documentation/REFERENCES.md` before release.", ""] + [f"- {t}" for t in tbv] + [""]
print("\n".join(out))
