# ---------------------------------------------------------------------------
# ARCAID3 lexicon view: one extra, optional way for the model to read the board.
#
# Adds to every frame in the Duck Python sandbox:
#   current_frame.code                  the board as objects: true cell size, a legend of symbols
#                                       (small multi-colour pictures with stable names), placements
#   current_frame.objects               the same as a list of dicts (symbol, row, col, size,
#                                       screen_row/screen_col of a cell to click with MOUSE)
#   current_frame.native                the board at its true resolution (e.g. 32x32, not 64x64)
#   current_frame.changes_since(frame)  objects that moved / appeared / disappeared / changed
# and tells the model about it.
#
# Version 2 (2026-10-04). Version 1 added the view and one sentence, and the model never used it:
# 0 of 1,130 tool calls (arcaid3/part3/WHY-THE-VIEW-WAS-NOT-USED.md). The harness's own prompt said a
# frame exposes "only" .ascii/.step/.level/.shape/.segmentation, three times per request. v2 changes:
#   1. those three "only" lines now list the new members (tool description + two system-prompt lines);
#   2. a "when" trigger next to the harness's "most recent change" line, in the style of F13's note;
#   3. on the first turn of a game and after a level change, one line in the user message:
#      start with print(current_frame.code).
# Each prompt edit is applied only if its anchor text is found exactly once; the READY line reports
# which edits applied. Nothing else changes: same images, actions, scheduling and serving.
#
# Kill switch: set ARCAID3_LEXICON=0 before this cell runs.
# Source of the embedded lexicon: arcaid3/part2/lexicon.py (stdlib only, no imports).
# Generated by arcaid3/part3/build.py -- edit the template and rebuild, not this cell.
#
# dfranzen port (2026-10-05, kaggle/lexicon-dfranzen/build.py): same lexicon, same sandbox methods,
# same view sizes. Three anchors changed for dfranzen's patched harness: the tool-description line
# (adds `.shape`), the trigger constant (PYTHON_ADDENDUM -> PYTHON_ADDENDUM_HEAD), and the new-level
# cue (LEVEL_START_USER_PROMPT under ARC3_LEVEL_TRANSFER_GUIDANCE=1).
#
# Version 2 (2026-10-07): per-level scale lock. The lexicon gains scale_lock(): one block size per
# level, agreed across that level's frames in `history`, so a sparse frame can no longer flip to a
# coarser grid and rename every object. Checked by its own sandbox self-test; ARCAID3_SCALE_LOCK=0 turns
# it off. The camera scale changes between levels in 4 of the 25 public games, so the lock is per level.
