    'up to fill 64x64. This module tries to undo that, using the screen alone:\n'
    '\n'
    '1. Native grid ("unzoom"): find the block size k the screen was scaled by, and\n'
    '   read the world back at its real resolution (e.g. 16x16 cells instead of\n'
    '   64x64 pixels).\n'
    '2. Objects: cut the world into pieces of touching non-background cells. Unlike\n'
    "   the Duck harness's `segmentation`, a piece may hold several colours, because\n"
    "   the games' own building blocks usually do.\n"
    '3. Lexicon: give every distinct picture a short symbol (A, B, C ...) that stays\n'
    '   the same across all frames of a game, and note when one symbol is just a\n'
    '   rotated or mirrored copy of another.\n'
    '4. Code: print the frame as a legend (symbol -> small picture) plus a list of\n'
    '   placements ("A at row 2, col 3"), and compare two frames as object moves\n'
    '   ("A moved right by 1") instead of cell flips.\n'
    '\n'
    'Rules this file keeps\n'
    '---------------------\n'
    '- Standard library only, no imports outside it, so its source can be pasted\n'
    "  into the Duck harness's Python sandbox (which runs `python -I -S`).\n"
    "- It reads only what an agent may read: the frame's colour grid. It never\n"
    '  touches game files or hidden engine state.\n'
    '- Deterministic: the same frames in the same order give the same symbols.\n'
    '"""\n'
    '\n'
    'DEFAULT_COLOR_CHARS = "WwgGcBMPRbSYOrNp"  # the Duck harness\'s ARC_COLOR_CHARS, index = colour value\n'
    'COLOR_NAMES = (\n'
    '    "white", "off-white", "light-grey", "grey", "dark-grey", "black", "magenta", "pink",\n'
    '    "red", "blue", "light-blue", "yellow", "orange", "maroon", "green", "purple",\n'
    ')\n'
    '\n'
    '\n'
    '# --------------------------------------------------------------------------- native grid\n'
    '\n'
    'def _boundaries(grid, axis):\n'
    '    """Positions where a row (axis 0) or column (axis 1) differs from the previous one."""\n'
    '    h, w = len(grid), len(grid[0])\n'
    '    out = []\n'
    '    if axis == 0:\n'
    '        for y in range(1, h):\n'
    '            if grid[y] != grid[y - 1]:\n'
    '                out.append(y)\n'
    '    else:\n'
    '        for x in range(1, w):\n'
    '            for y in range(h):\n'
    '                if grid[y][x] != grid[y][x - 1]:\n'
    '                    out.append(x)\n'
    '                    break\n'
    '    return out\n'
    '\n'
    '\n'
    'def _best_offset(bounds, k):\n'
    '    if not bounds:\n'
    '        return 0, 1.0\n'
    '    votes = [0] * k\n'
    '    for b in bounds:\n'
    '        votes[b % k] += 1\n'
    '    best = max(range(k), key=lambda r: (votes[r], -r))\n'
    '    return best, votes[best] / len(bounds)\n'
    '\n'
    '\n'
    'def _uniform_fraction(grid, k, oy, ox):\n'
    '    h, w = len(grid), len(grid[0])\n'
    '    total = uniform = 0\n'
    '    for by in range(oy, h - k + 1, k):\n'
    '        for bx in range(ox, w - k + 1, k):\n'
    '            v = grid[by][bx]\n'
    '            ok = True\n'
    '            for y in range(by, by + k):\n'
    '                row = grid[y]\n'
    '                for x in range(bx, bx + k):\n'
    '                    if row[x] != v:\n'
    '                        ok = False\n'
    '                        break\n'
    '                if not ok:\n'
    '                    break\n'
    '            total += 1\n'
    '            uniform += ok\n'
    '    return (uniform / total) if total else 0.0\n'
    '\n'
    '\n'
    'def _interior_runs(grid):\n'
    '    """Lengths of equal-colour runs along rows and columns that touch neither screen edge."""\n'
    '    h, w = len(grid), len(grid[0])\n'
    '    runs = []\n'
    '    for line in [grid[y] for y in range(h)] + [[grid[y][x] for y in range(h)] for x in range(w)]:\n'
    '        start = 0\n'
    '        for i in range(1, len(line) + 1):\n'
    '            if i == len(line) or line[i] != line[start]:\n'
    '                if start > 0 and i < len(line):\n'
    '                    runs.append(i - start)\n'
    '                start = i\n'
    '    return runs\n'
    '\n'
    '\n'
    'def _fits(grid, k, oy, ox, runs, min_runs, min_uniform):\n'
    '    """True when block size k at offset (oy, ox) passes both per-frame tests on this grid."""\n'
    '    if not runs or sum(1 for n in runs if n % k == 0) / len(runs) < min_runs:\n'
    '        return False\n'
    '    return _uniform_fraction(grid, k, oy, ox) >= min_uniform\n'
    '\n'
    '\n'
    'def _detect(grid, scales=(8, 7, 6, 5, 4, 3, 2), min_runs=0.85, min_uniform=0.75):\n'
    '    """Per-frame block size: (k, oy, ox, uniform share). (1, 0, 0, 1.0) when no scaling is found."""\n'
    '    h, w = len(grid), len(grid[0]) if grid else 0\n'
    '    rows_b, cols_b = _boundaries(grid, 0), _boundaries(grid, 1)\n'
    '    runs = _interior_runs(grid) if h and w else []\n'
    '    for k in scales:\n'
    '        if k * 2 > min(h, w) or not runs:\n'
    '            continue\n'
    '        if sum(1 for n in runs if n % k == 0) / len(runs) < min_runs:\n'
    '            continue\n'
    '        oy, _ = _best_offset(rows_b, k)\n'
    '        ox, _ = _best_offset(cols_b, k)\n'
    '        frac = _uniform_fraction(grid, k, oy, ox)\n'
    '        if frac >= min_uniform:\n'
    '            return (k, oy, ox, frac)\n'
    '    return (1, 0, 0, 1.0)\n'
    '\n'
    '\n'
    'def scale_lock(grids, scales=(8, 7, 6, 5, 4, 3, 2), min_runs=0.85, min_uniform=0.75, tolerance=0.0,\n'
    '               max_frames=256):\n'
    '    """One block size for a whole level, agreed across its frames.\n'
    '\n'
    '    A single sparse frame can look scaled by a coarser block than the game uses\n'
    '    (everything on it happens to line up at that size), and then every name on\n'
    '    that frame changes. The true block size passes the per-frame tests on every\n'
    '    frame of the level, while a spurious coarse one fails on a frame with finer\n'
    "    detail. So: take each frame's own detection as a candidate, and return the\n"
    '    largest candidate that passes both tests on every frame given, as (k, oy, ox);\n'
    '    `tolerance` is the share of frames allowed to fail (0 = strict).\n'
    '\n'
    '    All frames are used, not a sample, so the lock is monotone: once a frame has\n'
    '    rejected a block size, the level keeps it rejected and the lock cannot flip\n'
    "    back. Only the level's first frame and its last `max_frames - 1` frames are\n"
    '    read, to bound the cost. Pass frames of one level only: the camera scale can\n'
    '    change between levels (4 of the 25 public games do).\n'
    '    """\n'
    '    grids = [g for g in grids if g]\n'
    '    if not grids:\n'
    '        return None\n'
    '    if len(grids) > max_frames:\n'
    '        grids = grids[:1] + grids[-(max_frames - 1):]\n'
    '    grids = [[list(r) for r in g] for g in grids]\n'
    '    runs = [_interior_runs(g) for g in grids]\n'
    '    cands = {}\n'
    '    for g in grids:\n'
    '        k, oy, ox, _ = _detect(g, scales, min_runs, min_uniform)\n'
    '        if k > 1:\n'
    '            cands[(k, oy, ox)] = cands.get((k, oy, ox), 0) + 1\n'
    '    allowed = int(tolerance * len(grids))\n'
    '    for k, oy, ox in sorted(cands, key=lambda c: (-c[0], -cands[c], c[1], c[2])):\n'
    '        failed = 0\n'
    '        for g, r in zip(grids, runs):\n'
    '            if not _fits(g, k, oy, ox, r, min_runs, min_uniform):\n'
    '                failed += 1\n'
    '                if failed > allowed:\n'
    '                    break\n'
    '        if failed <= allowed:\n'
    '            return (k, oy, ox)\n'
    '    return (1, 0, 0)\n'
    '\n'
    '\n'
    'def native_grid(grid, scales=(8, 7, 6, 5, 4, 3, 2), min_runs=0.85, min_uniform=0.75, lock=None):\n'
    '    """Detect the scale-up block size and return the world at its native resolution.\n'
    '\n'
    '    A screen scaled up by k has colour runs whose lengths are multiples of k,\n'
    '    except where the game paints a HUD bar or counter over the picture. So k is\n'
    '    the largest block size that (a) divides at least `min_runs` of the interior\n'
    '    runs and (b) leaves at least `min_uniform` of the k x k blocks single-coloured.\n'
    '\n'
    '    Returns a dict:\n'
    '      scale       block size k (1 = no scaling found)\n'
    '      offset      (row, col) of the first block in screen pixels\n'
    '      cells       native grid, list of rows (majority colour of each k x k block)\n'
    '      uniform     share of blocks that are a single colour (1.0 = lossless)\n'
    '      residue     screen cells the upscaled native grid does not reproduce\n'
    '                  (HUD bars drawn over the scaled picture, odd margins)\n'
    '      locked      True when `lock` = (k, oy, ox) from `scale_lock` was used instead\n'
    "                  of this frame's own detection\n"
    '    """\n'
    '    grid = [list(r) for r in grid]\n'
    '    h, w = len(grid), len(grid[0]) if grid else 0\n'
    '    if lock and 1 <= lock[0] and lock[0] * 2 <= min(h, w):\n'
    '        k, oy, ox = lock\n'
    '        frac = _uniform_fraction(grid, k, oy, ox) if k > 1 else 1.0\n'
    '    else:\n'
    '        lock = None\n'
    '        k, oy, ox, frac = _detect(grid, scales, min_runs, min_uniform)\n'
    '    cells = []\n'
    '    for by in range(oy, h - k + 1, k):\n'
    '        row = []\n'
    '        for bx in range(ox, w - k + 1, k):\n'
    '            counts = {}\n'
    '            for y in range(by, by + k):\n'
    '                for x in range(bx, bx + k):\n'
    '                    counts[grid[y][x]] = counts.get(grid[y][x], 0) + 1\n'
    '            row.append(max(sorted(counts), key=lambda c: counts[c]))\n'
    '        cells.append(row)\n'
    '    residue = 0\n'
    '    nh, nw = len(cells), len(cells[0]) if cells else 0\n'
    '    for y in range(h):\n'
    '        for x in range(w):\n'
    '            ny, nx = (y - oy) // k, (x - ox) // k\n'
    '            inside = 0 <= y - oy and 0 <= x - ox and ny < nh and nx < nw\n'
    '            if not inside or cells[ny][nx] != grid[y][x]:\n'
    '                residue += 1\n'
    '    return {"scale": k, "offset": (oy, ox), "cells": cells, "uniform": round(frac, 4),\n'
    '            "residue": residue, "locked": lock is not None}\n'
    '\n'
    '\n'
    '# --------------------------------------------------------------------------- objects\n'
    '\n'
    '_N4 = ((-1, 0), (1, 0), (0, -1), (0, 1))\n'
    '_N8 = _N4 + ((-1, -1), (-1, 1), (1, -1), (1, 1))\n'
    '\n'
    '\n'
    'def background_colour(cells):\n'
    '    counts = {}\n'
    '    for row in cells:\n'
    '        for v in row:\n'
    '            counts[v] = counts.get(v, 0) + 1\n'
    '    return max(sorted(counts), key=lambda c: counts[c])\n'
    '\n'
    '\n'
    'def objects(cells, background=None, connectivity=8, multicolour=True):\n'
    '    """Connected pieces of non-background cells.\n'
    '\n'
    "    multicolour=True joins touching cells of any colours (the lexicon's view);\n"
    "    multicolour=False joins only equal colours (like the Duck harness's view).\n"
    '    Each object: {"cells": [(r, c), ...] sorted, "bbox": (r0, c0, r1, c1), "colours": [...]}.\n'
    '    """\n'
    '    if background is None:\n'
    '        background = background_colour(cells)\n'
    '    h, w = len(cells), len(cells[0]) if cells else 0\n'
    '    nbrs = _N8 if connectivity == 8 else _N4\n'
    '    seen = [[False] * w for _ in range(h)]\n'
    '    out = []\n'
    '    for sr in range(h):\n'
    '        for sc in range(w):\n'
    '            if seen[sr][sc] or cells[sr][sc] == background:\n'
    '                continue\n'
    '            colour = cells[sr][sc]\n'
    '            stack, members = [(sr, sc)], []\n'
    '            seen[sr][sc] = True\n'
    '            while stack:\n'
    '                r, c = stack.pop()\n'
    '                members.append((r, c))\n'
    '                for dr, dc in nbrs:\n'
    '                    nr, nc = r + dr, c + dc\n'
    '                    if 0 <= nr < h and 0 <= nc < w and not seen[nr][nc]:\n'
    '                        v = cells[nr][nc]\n'
    '                        if v != background and (multicolour or v == colour):\n'
    '                            seen[nr][nc] = True\n'
    '                            stack.append((nr, nc))\n'
    '            members.sort()\n'
    '            rs = [p[0] for p in members]\n'
    '            cs = [p[1] for p in members]\n'
    '            out.append({\n'
    '                "cells": members,\n'
    '                "bbox": (min(rs), min(cs), max(rs), max(cs)),\n'
    '                "colours": sorted({cells[r][c] for r, c in members}),\n'
    '            })\n'
    '    return out\n'
    '\n'
    '\n'
    'def layered_objects(cells, background=None, connectivity=8, min_container=24, depth=3):\n'
    '    """Objects with floors peeled off: the lexicon\'s default view.\n'
    '\n'
    '    Games draw small sprites on top of large ones (a floor, a panel, a board).\n'
    '    A flat cut glues everything on a floor into one piece. Here, a large\n'
    '    multi-colour piece is treated as a container: its most common colour is its\n'
    '    local floor, the floor cells become one object, and the cells that sit on it\n'
    '    are cut again (up to `depth` levels). Each object gets a "depth" and, below\n'
    '    the top, the index of its container ("parent").\n'
    '    """\n'
    '    if background is None:\n'
    '        background = background_colour(cells)\n'
    '    h, w = len(cells), len(cells[0]) if cells else 0\n'
    '    out = []\n'
    '\n'
    '    def cut(pieces, level, parent):\n'
    '        for obj in pieces:\n'
    '            members = obj["cells"]\n'
    '            if level >= depth or len(members) < min_container or len(obj["colours"]) < 2:\n'
    '                out.append(dict(obj, depth=level, parent=parent))\n'
    '                continue\n'
    '            counts = {}\n'
    '            for r, c in members:\n'
    '                counts[cells[r][c]] = counts.get(cells[r][c], 0) + 1\n'
    '            floor = max(sorted(counts), key=lambda v: counts[v])\n'
    '            floor_cells = sorted(p for p in members if cells[p[0]][p[1]] == floor)\n'
    '            rest = set(members) - set(floor_cells)\n'
    '            if not rest:\n'
    '                out.append(dict(obj, depth=level, parent=parent))\n'
    '                continue\n'
    '            masked = [[-99] * w for _ in range(h)]\n'
    '            for r, c in rest:\n'
    '                masked[r][c] = cells[r][c]\n'
    '            rs = [p[0] for p in floor_cells]\n'
    '            cs = [p[1] for p in floor_cells]\n'
    '            me = len(out)\n'
    '            out.append({"cells": floor_cells, "bbox": (min(rs), min(cs), max(rs), max(cs)),\n'
    '                        "colours": [floor], "depth": level, "parent": parent, "container": True})\n'
    '            cut(objects(masked, -99, connectivity=connectivity, multicolour=True), level + 1, me)\n'
    '\n'
    '    cut(objects(cells, background, connectivity=connectivity, multicolour=True), 0, None)\n'
    '    return out\n'
    '\n'
    '\n'
    '# --------------------------------------------------------------------------- lexicon\n'
    '\n'
    'def _patch(cells, obj):\n'
    '    r0, c0, r1, c1 = obj["bbox"]\n'
    '    member = set(obj["cells"])\n'
    '    return tuple(\n'
    '        tuple(cells[r][c] if (r, c) in member else -1 for c in range(c0, c1 + 1))\n'
    '        for r in range(r0, r1 + 1)\n'
    '    )\n'
    '\n'
    '\n'
    'def _rot90(p):  # clockwise\n'
    '    return tuple(tuple(p[len(p) - 1 - r][c] for r in range(len(p))) for c in range(len(p[0])))\n'
    '\n'
    '\n'
    'def _mirror(p):\n'
    '    return tuple(tuple(reversed(row)) for row in p)\n'
    '\n'
    '\n'
    'def _variants(p):\n'
    '    """The 8 rotations/mirrors of a patch, with a readable name for each."""\n'
    '    out, cur = [], p\n'
    '    for k in range(4):\n'
    '        out.append((f"rot{90 * k}", cur))\n'
    '        out.append((f"mirror+rot{90 * k}", _mirror(cur)))\n'
    '        cur = _rot90(cur)\n'
    '    return out\n'
    '\n'
    '\n'
    'def _symbol_name(i):\n'
    '    s = ""\n'
    '    i += 1\n'
    '    while i:\n'
    '        i, r = divmod(i - 1, 26)\n'
    '        s = chr(65 + r) + s\n'
    '    return s\n'
    '\n'
    '\n'
    'def _stable_name(patch, color_chars):\n'
    '    """Content-derived name: dominant colour letter + 3 hex digits of the picture\'s hash.\n'
    '\n'
    '    Python hashes tuples of ints the same way in every process (only str/bytes\n'
    '    hashing is randomised), so a fresh sandbox process names a picture the same\n'
    '    way every time without any saved state.\n'
    '    """\n'
    '    counts = {}\n'
    '    for row in patch:\n'
    '        for v in row:\n'
    '            if v >= 0:\n'
    '                counts[v] = counts.get(v, 0) + 1\n'
    '    dom = max(sorted(counts), key=lambda c: counts[c]) if counts else 0\n'
    '    return f"{color_chars[dom]}{hash(patch) & 0xFFF:03x}"\n'
    '\n'
    '\n'
    'class Lexicon:\n'
    '    """Persistent symbol table for one game: picture -> symbol.\n'
    '\n'
    '    naming="sequential" gives A, B, C ... in order of first sight (readable; needs\n'
    '    one Lexicon kept across frames). naming="stable" gives content-derived names\n'
    '    such as "R3fa" that come out the same in any process (for the Duck sandbox,\n'
    '    which starts a fresh process for every tool call).\n'
    '    """\n'
    '\n'
    '    def __init__(self, color_chars=DEFAULT_COLOR_CHARS, naming="sequential"):\n'
    '        self.color_chars = color_chars\n'
    '        self.naming = naming\n'
    '        self.by_key = {}      # exact patch -> symbol\n'
    '        self.entries = {}     # symbol -> {"patch", "count", "first_seen", "family", "pose"}\n'
    '        self.by_canon = {}    # rotation/mirror-canonical patch -> first symbol with that shape\n'
    '\n'
    '    def symbol_for(self, patch, seen_at=None):\n'
    '        sym = self.by_key.get(patch)\n'
    '        if sym is None:\n'
    '            if self.naming == "stable":\n'
    '                sym = base = _stable_name(patch, self.color_chars)\n'
    '                n = 1\n'
    '                while sym in self.entries:        # rare: two pictures share a fingerprint\n'
    '                    n += 1\n'
    '                    sym = f"{base}_{n}"\n'
    '            else:\n'
    '                sym = _symbol_name(len(self.entries))\n'
    '            variants = _variants(patch)\n'
    '            canon_name, canon = min(variants, key=lambda v: v[1])\n'
