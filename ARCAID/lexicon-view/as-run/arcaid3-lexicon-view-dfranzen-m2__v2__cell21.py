def _arcaid3_grid(view):
    grid = getattr(view, "_grid", None) or []
    if grid:
        return grid
    index = {ch: i for i, ch in enumerate(COLOR_CHARS)}
    return [[index.get(ch, 0) for ch in line] for line in str(getattr(view, "ascii", "")).split("\\n") if line]


def _arcaid3_lexicon():
    return _ARCAID3["Lexicon"](COLOR_CHARS or _ARCAID3["DEFAULT_COLOR_CHARS"], naming="stable")


_ARCAID3_SCALE_LOCK = __LOCK__
_ARCAID3_LOCKS = {}


def _arcaid3_runtime():
    """The globals of the snippet that asked (they hold `history` and `current_frame`)."""
    f = sys._getframe(1)
    while f is not None:
        g = f.f_globals
        if "history" in g and "current_frame" in g:
            return g
        f = f.f_back
    return None


def _arcaid3_lock(view):
    """One block size for the level `view` is on, agreed across that level's frames in `history`.

    The sandbox starts a fresh process for every call, so the lock is recomputed from the frames
    each call can see, and cached for the rest of the call. None means: use per-frame detection.
    """
    if not _ARCAID3_SCALE_LOCK or "scale_lock" not in _ARCAID3:
        return None
    level = getattr(view, "level", None)
    rt = _arcaid3_runtime()
    if level is None or rt is None:
        return None
    frames = [getattr(e, "frame", None) for e in (rt.get("history") or [])]
    frames = [fr for fr in frames if fr is not None and getattr(fr, "level", None) == level]
    for extra in (rt.get("current_frame"), view):
        if extra is not None and getattr(extra, "level", None) == level and not any(extra is fr for fr in frames):
            frames.append(extra)
    key = (level, len(frames), id(frames[0]), id(frames[-1]))
    if key not in _ARCAID3_LOCKS:
        try:
            _ARCAID3_LOCKS[key] = _ARCAID3["scale_lock"]([_arcaid3_grid(fr) for fr in frames])
        except Exception:
            _ARCAID3_LOCKS[key] = None
    return _ARCAID3_LOCKS[key]


def _arcaid3_encode(view, lex=None):
    return _ARCAID3["encode"](_arcaid3_grid(view), lex if lex is not None else _arcaid3_lexicon(),
                              lock=_arcaid3_lock(view))

