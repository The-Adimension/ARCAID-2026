    '\n'
    'What it does, in plain words\n'
    '----------------------------\n'
    'An ARC-AGI-3 screen is a 64x64 grid of colour numbers (0-15). The official games\n'
    'are not drawn pixel by pixel: each level is a small world of named "sprites"\n'
