def arcaid3_apply_prompt_edits(modules):
    """Apply ARCAID3_PROMPT_EDITS to the named string constants of each module. Idempotent.

    Returns {edit name: "applied" | "already" | "anchor found N times"}. An edit whose anchor is not
    found exactly once is skipped, never forced.
    """
    result = {}
    for name, const, old, new in ARCAID3_PROMPT_EDITS:
        status = None
        for mod in modules:
            text = getattr(mod, const, None)
            if not isinstance(text, str):
                continue
            if new in text:
                status = status or "already"
                continue
            found = text.count(old)
            if found != 1:
                status = status or f"anchor found {found} times"
                continue
            setattr(mod, const, text.replace(old, new))
            status = "applied"
        result[name] = status or "constant missing"
    return result


def arcaid3_wrap_user_prompt(agent_cls):
    """Add ARCAID3_CUE to the user message on a game's first turn and after a level change."""
    orig = agent_cls._build_user_prompt
    if getattr(orig, "_arcaid3", False):
        return False

    def _build_user_prompt(self, *args, **kwargs):
        text = orig(self, *args, **kwargs)
        try:
            if isinstance(text, str) and ARCAID3_CUE not in text and any(w in text for w in _A3_CUE_WHEN):
                text = text + "\n" + ARCAID3_CUE
                ARCAID3_STATS["cue_turns"] += 1
        except Exception:
            ARCAID3_STATS["errors"] += 1
        return text

    _build_user_prompt._arcaid3 = True
    agent_cls._build_user_prompt = _build_user_prompt
    return True


def arcaid3_patch_sandbox_source(source):
    """Return the sandbox program with the lexicon view added.

    Raises if an anchor is not found exactly once; the caller then leaves the stock
    sandbox alone rather than spawning a broken one. Idempotent.
    """
    text = str(source)
    if "_arcaid3_encode" in text:
        return text
    for anchor in (_A3_ANCHOR_GLOBALS, _A3_ANCHOR_METHODS):
        found = text.count(anchor)
        if found != 1:
            raise RuntimeError(f"anchor found {found} times, expected 1: {anchor.splitlines()[-1]!r}")
    text = text.replace(_A3_ANCHOR_GLOBALS,
                        _A3_SB_GLOBALS.replace("__SRC__", repr(ARCAID3_LEXICON_SOURCE)) + "\n" + _A3_ANCHOR_GLOBALS)
    text = text.replace(_A3_ANCHOR_METHODS, _A3_SB_METHODS + _A3_ANCHOR_METHODS)
    compile(text, "<sandbox>", "exec")                 # never ship an unparsable child program
    return text


def _arcaid3_self_test(sb):
    """Run the real sandbox once on a tiny scaled board and check the view answers."""
    big = [[5] * 64 for _ in range(64)]
    for r in range(8, 14):                            # a 3x3 two-colour object, drawn at 2x scale
        for c in range(8, 14):
            big[r][c] = 8
    for r in range(10, 12):
        for c in range(10, 12):
            big[r][c] = 9
    moved = [row[:] for row in big]
    for r in range(8, 14):
        for c in range(8, 14):
            moved[r][c] = 5
    for r in range(8, 14):
        for c in range(12, 18):
            moved[r][c] = big[r][c - 4]
    chars = sb.ARC_COLOR_CHARS

    def frame(g, step):
        return {"ascii": "\n".join("".join(chars[v] for v in row) for row in g), "step": step, "level": 1,
                "shape": [64, 64], "grid": g}

    state = {"current_frame": frame(moved, 2),
             "history": [{"action": "RESET", "frame": frame(big, 1)}, {"action": "RIGHT", "frame": frame(moved, 2)}],
             "last_action_result": {}, "valid_actions": ["RIGHT"]}
    code = ("print(current_frame.code)\n"
            "print(current_frame.changes_since(previous_frame))\n"
            "print(current_frame.objects[0]['screen_row'], current_frame.objects[0]['screen_col'])\n")
    res = sb.run_sandboxed_python(code=code, timeout_seconds=30, initial_state=state,
                                  action_handler=lambda actions: {})
    out = str(res.get("stdout", ""))
    ok = ("world 32x32 cells, each cell 2x2 px" in out and "moved (4, 4)->(4, 6)" in out
          and "OBJECTS 1 in 1 kinds" in out and not res.get("error"))
    return ok, out, res.get("error")


def install_arcaid3_lexicon():
    report = {"enabled": ARCAID3_ON, "installed": False}
    if not ARCAID3_ON:
        return report
    import inference.agent.python_tool_sandbox as _a3_sb
    import inference.agent.tool_agent as _a3_ta

    try:
        patched = arcaid3_patch_sandbox_source(_a3_sb._SANDBOX_BOOTSTRAP)
    except Exception as exc:                          # stock sandbox stays in place
        report["error"] = f"sandbox patch: {type(exc).__name__}: {exc}"
        return report
    stock = _a3_sb._SANDBOX_BOOTSTRAP
    _a3_sb._SANDBOX_BOOTSTRAP = patched
    ok, out, err = _arcaid3_self_test(_a3_sb)
    if not ok:                                        # roll back: the run continues exactly as stock
        _a3_sb._SANDBOX_BOOTSTRAP = stock
        report["error"] = f"self-test failed: {err!r} :: {out[:400]!r}"
        return report

    if ARCAID3_NOTE not in _a3_ta.STRUCTURED_RUNTIME_STATE_ADDENDUM:
        _a3_ta.STRUCTURED_RUNTIME_STATE_ADDENDUM = _a3_ta.STRUCTURED_RUNTIME_STATE_ADDENDUM + ARCAID3_NOTE

    # v2: the harness's prompt text, edited in both modules (tool_agent imported the constants by name)
    import inference.agent.prompts as _a3_pr
    report["prompt_edits"] = arcaid3_apply_prompt_edits([_a3_ta, _a3_pr])
    report["first_turn_cue"] = "installed" if arcaid3_wrap_user_prompt(_a3_ta.ToolAgent) else "already"

    # observe-only usage counter on the function the agent calls (tool_agent imported it by name)
    if not getattr(_a3_ta.run_sandboxed_python, "_arcaid3", False):
        _orig_run = _a3_ta.run_sandboxed_python

        def run_sandboxed_python(*args, **kwargs):
            try:
                src = str(kwargs.get("code", ""))
                ARCAID3_STATS["tool_calls"] += 1
                used = False
                for key, needle in (("code", ".code"), ("objects", ".objects"), ("native", ".native"),
                                    ("changes_since", ".changes_since(")):
                    if needle in src:
                        ARCAID3_STATS[key] += 1
                        used = True
                ARCAID3_STATS["calls_using_view"] += int(used)
                if ARCAID3_STATS["tool_calls"] % 200 == 0:
                    print("ARCAID3_LEXICON_STATS", ARCAID3_STATS, flush=True)
            except Exception:
                ARCAID3_STATS["errors"] += 1
            return _orig_run(*args, **kwargs)

        run_sandboxed_python._arcaid3 = True
        _a3_ta.run_sandboxed_python = run_sandboxed_python
    report["installed"] = True
    report["self_test"] = "ok"
    return report


ARCAID3_REPORT = install_arcaid3_lexicon()
print("ARCAID3_LEXICON_READY" if ARCAID3_REPORT.get("installed") else "ARCAID3_LEXICON_OFF",
      ARCAID3_REPORT, flush=True)
